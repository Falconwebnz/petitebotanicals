function fillContact(text, email) {
  const address = String(email || '').trim();
  const source = String(text || '');
  if (address) return source.replaceAll('{{email}}', address);
  return source
    .replace(/write to us at \{\{email\}\}/gi, (phrase) => {
      const lead = phrase.charAt(0) === 'W' ? 'W' : 'w';
      return lead + 'rite to us using the contact details on your order confirmation';
    })
    .replaceAll('{{email}}', 'the contact details on your order confirmation');
}

function segments(text, email) {
  const filled = fillContact(text, email);
  const address = String(email || '').trim();
  const parts = [];
  const link = /\[([^\]]+)\]\(([^)\s]+)\)/g;
  let last = 0;
  let match;
  while ((match = link.exec(filled))) {
    if (match.index > last) parts.push({ type: 'text', value: filled.slice(last, match.index) });
    const href = match[2].trim();
    if (/^(https:\/\/|\/)/.test(href)) parts.push({ type: 'link', value: match[1], href });
    else parts.push({ type: 'text', value: match[0] });
    last = match.index + match[0].length;
  }
  if (last < filled.length) parts.push({ type: 'text', value: filled.slice(last) });
  if (!address) return parts.length ? parts : [{ type: 'text', value: '' }];
  return parts.flatMap((part) => {
    if (part.type !== 'text' || !part.value.includes(address)) return [part];
    const bits = part.value.split(address);
    const out = [];
    bits.forEach((bit, index) => {
      if (bit) out.push({ type: 'text', value: bit });
      if (index < bits.length - 1) out.push({ type: 'email', value: address });
    });
    return out;
  });
}

function headingId(text, used) {
  const base = String(text || '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'section';
  let id = base;
  let n = 2;
  while (used.has(id)) {
    id = base + '-' + n;
    n += 1;
  }
  used.add(id);
  return id;
}

function buttonLabel(raw) {
  const text = String(raw || '').replace(/\s+/g, ' ').trim();
  if (text && text === text.toUpperCase()) {
    return text.charAt(0) + text.slice(1).toLowerCase();
  }
  return text;
}

function buttonHref(raw) {
  const label = String(raw || '').toLowerCase();
  if (label.includes('story')) return '/about';
  if (label.includes('glossar') || label.includes('ingredient')) return '/glossary';
  if (label.includes('return')) return '/returns';
  if (label.includes('standard')) return '/standards';
  return '/shop';
}

function isSubheading(line) {
  const text = String(line || '').trim();
  if (!text || text.length > 48) return false;
  if (/[.!?:;]$/.test(text)) return false;
  if (/@|https?:\/\/|^BUTTON:/i.test(text)) return false;
  if (/^\[.+\]\([^)]+\)$/.test(text)) return false;
  const words = text.split(/\s+/);
  if (words.length > 7) return false;
  if (/\bthe\b/i.test(text)) return false;
  if (/^(for|write|please|we|you|the|our|this|where|an|a|and)\b/i.test(text)) return false;
  if (/\b(write|tell|send|email|pay|refund)\b/i.test(text)) return false;
  if (!/^[A-Z0-9“"]/.test(text)) return false;
  return true;
}

function parsePolicy(raw, email) {
  const lines = String(raw || '').replace(/\r\n/g, '\n').split('\n');
  const blocks = [];
  const toc = [];
  const used = new Set();
  let para = [];
  let list = null;

  function flushPara() {
    if (!para.length) return;
    const text = para.join(' ').replace(/\s+/g, ' ').trim();
    para = [];
    if (text) blocks.push({ type: 'p', parts: segments(text, email) });
  }

  function flushList() {
    if (!list || !list.length) {
      list = null;
      return;
    }
    blocks.push({ type: 'ul', items: list });
    list = null;
  }

  lines.forEach((line, index) => {
    const trimmed = line.trim();
    const heading = trimmed.match(/^#\s+(.+)$/);
    if (!trimmed) {
      flushPara();
      flushList();
      return;
    }
    if (heading) {
      flushPara();
      flushList();
      const text = heading[1].trim();
      const id = headingId(text, used);
      blocks.push({ type: 'h2', id, text });
      toc.push({ id, text });
      return;
    }
    if (/^[-•]\s+/.test(trimmed)) {
      flushPara();
      if (!list) list = [];
      list.push(segments(trimmed.replace(/^[-•]\s+/, ''), email));
      return;
    }
    const onlyLink = trimmed.match(/^\[([^\]]+)\]\(([^)\s]+)\)$/);
    if (onlyLink && /^(https:\/\/|\/)/.test(onlyLink[2].trim())) {
      flushPara();
      flushList();
      blocks.push({ type: 'button', text: onlyLink[1].trim(), href: onlyLink[2].trim() });
      return;
    }
    if (/^BUTTON:/i.test(trimmed)) {
      flushPara();
      flushList();
      trimmed.split(/BUTTON:/i).map((part) => part.trim()).filter(Boolean).forEach((label) => {
        blocks.push({ type: 'button', text: buttonLabel(label), href: buttonHref(label) });
      });
      return;
    }
    if (isSubheading(trimmed)) {
      let next = '';
      for (let i = index + 1; i < lines.length; i += 1) {
        const candidate = lines[i].trim();
        if (candidate) {
          next = candidate;
          break;
        }
      }
      if (next && !isSubheading(next)) {
        flushPara();
        flushList();
        const id = headingId(trimmed, used);
        blocks.push({ type: 'h2', id, text: trimmed });
        toc.push({ id, text: trimmed });
        return;
      }
    }
    flushList();
    para.push(trimmed);
  });
  flushPara();
  flushList();
  return { blocks, toc };
}

function aboutBlocks(raw) {
  const lines = String(raw || '').replace(/\r\n/g, '\n').split('\n').map((line) => line.trim());
  const blocks = [];
  let list = null;
  lines.forEach((line, index) => {
    if (!line) {
      list = null;
      return;
    }
    if (/^[-•]\s+/.test(line)) {
      if (!list) {
        list = { type: 'ul', items: [] };
        blocks.push(list);
      }
      list.items.push(segments(line.replace(/^[-•]\s+/, '')));
      return;
    }
    list = null;
    const marked = line.match(/^#{1,3}\s+(.+)$/);
    const next = lines.slice(index + 1).find(Boolean) || '';
    if (marked) blocks.push({ type: 'h3', text: marked[1].trim() });
    else if (next && isSubheading(line) && !isSubheading(next)) blocks.push({ type: 'h3', text: line });
    else blocks.push({ type: 'p', parts: segments(line) });
  });
  return blocks;
}

function glossaryAnchor(term, used) {
  let id = String(term || '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'term';
  const base = id;
  let n = 2;
  while (used.has(id)) {
    id = base + '-' + n;
    n += 1;
  }
  used.add(id);
  return id;
}

function parseGlossary(raw) {
  const used = new Set();
  return String(raw || '')
    .replace(/\r\n/g, '\n')
    .split(/\n{2,}/)
    .map((block) => {
      const lines = block.split('\n').map((line) => line.trim()).filter(Boolean);
      if (!lines.length) return null;
      const term = lines[0].replace(/^#+\s*/, '').trim();
      let start = 1;
      let inci = '';
      if (lines[1] && /^inci\s*:/i.test(lines[1])) {
        inci = lines[1].replace(/^inci\s*:\s*/i, '').trim();
        start = 2;
      }
      const body = lines.slice(start).join(' ').replace(/\s+/g, ' ').trim();
      if (!term) return null;
      return { term, inci, body, id: glossaryAnchor(term, used) };
    })
    .filter(Boolean);
}

function groupGlossary(entries) {
  const groups = [];
  const byLetter = {};
  entries.forEach((entry) => {
    const letter = (entry.term.trim().charAt(0) || '#').toUpperCase();
    if (!byLetter[letter]) {
      byLetter[letter] = { letter, id: 'letter-' + encodeURIComponent(letter), entries: [] };
      groups.push(byLetter[letter]);
    }
    byLetter[letter].entries.push(entry);
  });
  groups.sort((a, b) => a.letter.localeCompare(b.letter));
  groups.forEach((group) => {
    group.entries.sort((a, b) => a.term.localeCompare(b.term));
  });
  return groups;
}

